"""接口文档的 Markdown 渲染（纯函数，无副作用）。

REST / CLI / MCP 三个出口复用同一份渲染逻辑，避免文档格式各写一套。
"""

from __future__ import annotations

from collections import Counter
from datetime import UTC, datetime

from app.interface_registry.schemas import InterfaceInfo


def format_signature(info: InterfaceInfo) -> str:
    """生成人类可读的函数签名。"""
    parts: list[str] = []
    keyword_separator = False
    for index, param in enumerate(info.params):
        if param.kind == "keyword_only" and not keyword_separator:
            parts.append("*")
            keyword_separator = True
        if param.name.startswith("*"):
            keyword_separator = True
        text = param.name
        if param.annotation:
            text += f": {param.annotation}"
        if param.default is not None:
            text += f" = {param.default}"
        parts.append(text)
        if param.kind == "positional_only" and (
            index + 1 == len(info.params) or info.params[index + 1].kind != "positional_only"
        ):
            parts.append("/")

    if info.kind == "class":
        prefix = "class "
    elif info.is_async:
        prefix = "async def "
    else:
        prefix = "def "

    signature = f"{prefix}{info.name}({', '.join(parts)})"
    if info.returns:
        signature += f" -> {info.returns}"
    return signature


_MARKDOWN_COPY: dict[str, dict[str, str]] = {
    "zh": {
        "title": "# TeamCode 接口文档",
        "project": "项目 ID",
        "generated": "生成时间",
        "interfaces": "接口总数",
        "modules": "模块数",
        "versions": "版本摘要",
        "none": "无",
        "usage": "> **使用说明**：本文档由 Interface Registry 基于 Python AST 自动生成，"
        "是接口的唯一事实来源。Coding Agent 在开发前应以此文档为准，"
        "不要自行猜测接口名称、参数或返回类型。",
        "empty": "_当前项目尚未注册任何接口。_",
        "module": "## 模块 `{module}`",
        "type": "类型",
        "file": "文件",
        "version": "版本",
        "commit": "提交",
        "decorators": "装饰器",
    },
    "en": {
        "title": "# TeamCode Interface Docs",
        "project": "Project ID",
        "generated": "Generated at",
        "interfaces": "Interfaces",
        "modules": "Modules",
        "versions": "Version summary",
        "none": "none",
        "usage": "> **Usage**: This document is generated by the Interface Registry "
        "from Python AST and is the single source of truth. Coding Agents must "
        "follow it instead of guessing interface names, parameters, or return types.",
        "empty": "_No interfaces are registered for this project yet._",
        "module": "## Module `{module}`",
        "type": "Type",
        "file": "File",
        "version": "Version",
        "commit": "Commit",
        "decorators": "Decorators",
    },
}


def render_markdown(
    project_id: str,
    interfaces: list[InterfaceInfo],
    *,
    generated_at: datetime | None = None,
    locale: str = "zh",
) -> str:
    """渲染可直接交给 Coding Agent 阅读的接口文档。"""
    copy = _MARKDOWN_COPY.get(locale or "zh", _MARKDOWN_COPY["zh"])
    generated_at = generated_at or datetime.now(UTC)
    sorted_interfaces = sorted(
        interfaces,
        key=lambda i: (i.module, i.lineno or 0, i.name, i.kind),
    )

    version_counter = Counter(i.version for i in sorted_interfaces)
    version_summary = (
        ", ".join(f"v{version} × {count}" for version, count in sorted(version_counter.items()))
        or copy["none"]
    )
    modules = sorted({i.module for i in sorted_interfaces})

    lines: list[str] = [
        copy["title"],
        "",
        f'> {copy["project"]}: `{project_id}`  ',
        f'> {copy["generated"]}: {generated_at.isoformat()}  ',
        f'> {copy["interfaces"]}: {len(sorted_interfaces)}  |  '
        f'{copy["modules"]}: {len(modules)}  |  '
        f'{copy["versions"]}: {version_summary}',
        "",
        copy["usage"],
        "",
    ]

    if not sorted_interfaces:
        lines.append(copy["empty"])
        lines.append("")
        return "\n".join(lines)

    for module in modules:
        module_items = [i for i in sorted_interfaces if i.module == module]
        lines.append(copy["module"].format(module=module))
        lines.append("")

        for info in module_items:
            lines.append(f"### `{info.name}`")
            lines.append("")
            lines.append("```python")
            lines.append(format_signature(info))
            lines.append("```")
            lines.append("")
            lines.append(f'- {copy["type"]}: `{info.kind}`')
            lines.append(f'- {copy["file"]}: `{info.file_path}`')
            lines.append(f'- {copy["version"]}: `v{info.version}`')
            if info.commit_hash:
                lines.append(f'- {copy["commit"]}: `{info.commit_hash}`')
            if info.decorators:
                decorators = ", ".join(f"`@{d}`" for d in info.decorators)
                lines.append(f'- {copy["decorators"]}: {decorators}')
            if info.docstring:
                lines.append("")
                lines.append(info.docstring.strip())
            lines.append("")

    return "\n".join(lines)
