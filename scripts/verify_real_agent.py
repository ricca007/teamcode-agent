"""Opt-in Claude Code smoke test. Uses account quota; never part of pytest."""

import argparse
import json
import os
import shutil
import socket
import subprocess
import sys
import time
from datetime import UTC, datetime
from pathlib import Path
from urllib.error import URLError
from urllib.request import Request, urlopen

from run_mvp import prepare

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--claude", default=shutil.which("claude"))
    parser.add_argument(
        "--output", type=Path, default=ROOT / "docs/real-agent-verification.json"
    )
    args = parser.parse_args()
    if not args.claude:
        parser.error("Claude Code not found; supply --claude and log in first")
    stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
    data = ROOT / ".mvp" / ("real-agent-" + stamp)
    repo = prepare(data)
    # Acceptance tests are supplied by the evaluator, not generated by the agent.
    (repo / "tests/test_agent_feature.py").write_text(
        "import pytest\n"
        "from backend.app.modules.user.normalization import normalize_username\n"
        "@pytest.mark.parametrize('value,expected', [(' Alice ', 'alice'), "
        "('BOB', 'bob'), ('张三', '张三')])\n"
        "def test_normalize(value, expected):\n"
        "    assert normalize_username(value) == expected\n"
        "def test_empty():\n"
        "    with pytest.raises(ValueError): normalize_username('  ')\n",
        encoding="utf-8",
    )
    for command in (
        ["add", "."],
        ["commit", "-m", "add independent agent acceptance tests"],
    ):
        subprocess.run(
            [
                "git",
                "-c",
                "user.name=TeamCode MVP",
                "-c",
                "user.email=mvp@example.invalid",
                *command,
            ],
            cwd=repo,
            check=True,
            capture_output=True,
        )
    instruction = (
        "This is a small real-adapter acceptance task. Implement ONLY "
        "backend/app/modules/user/normalization.py with "
        "normalize_username(value: str) -> str: strip surrounding whitespace, "
        "lowercase, and raise ValueError for an empty result. Read the supplied "
        "interface documentation in the prompt. Preserve existing get_user. "
        "Do not modify tests or any other file, do not commit, do not use Bash. "
        "Use Read/Write/Edit to create this file and finish. The platform runs tests."
    )
    command = [
        args.claude,
        "--print",
        "--tools",
        "Read,Write,Edit",
        "--allowedTools",
        "Read,Write,Edit",
        "--no-session-persistence",
        "--max-budget-usd",
        "2",
        "--model",
        "sonnet",
        "--append-system-prompt",
        instruction,
        "--output-format",
        "text",
    ]
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        port = sock.getsockname()[1]
    env = {
        **os.environ,
        "PYTHONUTF8": "1",
        "TEAMCODE_LLM_AUTO": "0",
        "DATABASE_URL": f"sqlite+aiosqlite:///{data / 'mvp.db'}",
        "TEAMCODE_AGENTS": json.dumps(
            {"claude": {"command": command, "prompt_mode": "stdin", "timeout": 240}}
        ),
    }
    base = f"http://127.0.0.1:{port}"
    report = {
        "agent": "Claude Code",
        "adapter": "B CLIAdapter via C REST",
        "date_utc": stamp,
        "model_requested": "sonnet",
        "budget_limit_usd": 2,
        "checks": [],
        "passed": False,
    }

    def check(name, condition):
        report["checks"].append({"name": name, "passed": bool(condition)})
        print(f"[{'PASS' if condition else 'FAIL'}] {name}", flush=True)
        if not condition:
            raise AssertionError(name)

    def http(path, token="", body=None):
        request = Request(
            base + path,
            method="POST" if body is not None else "GET",
            data=json.dumps(body).encode() if body is not None else None,
            headers={
                "Authorization": "Bearer " + token,
                "Content-Type": "application/json",
            },
        )
        with urlopen(request, timeout=40) as response:
            return json.load(response)

    with (data / "server.log").open("w", encoding="utf-8") as log:
        process = subprocess.Popen(
            [
                sys.executable,
                str(ROOT / "scripts/run_mvp.py"),
                "--port",
                str(port),
                "--data-dir",
                str(data),
            ],
            cwd=ROOT,
            env=env,
            stdout=log,
            stderr=log,
        )
        try:
            for _ in range(150):
                try:
                    http("/health")
                    break
                except (URLError, OSError):
                    if process.poll() is not None:
                        raise RuntimeError("Server failed; inspect retained server.log")
                    time.sleep(0.1)
            token = http("/api/demo")["members"][0]["token"]
            task = next(
                t
                for t in http("/api/projects/p_demo/tasks", token)["tasks"]
                if t["task_id"].endswith("task_user")
            )
            path = f"/api/tasks/{task['task_id']}"
            http(path + "/run", token, {"agent_name": "claude"})
            start = time.monotonic()
            while time.monotonic() - start < 270:
                state = http(path + "/status", token)
                if state["status"] in {"succeeded", "failed", "terminated"}:
                    break
                time.sleep(1)
            report["status"] = state["status"]
            report["elapsed_seconds"] = round(time.monotonic() - start, 2)
            logs = http(path + "/logs", token)["logs"]
            # Keep local diagnostic logs; never put auth/session tokens in the report.
            (data / "agent-logs.json").write_text(
                json.dumps(logs, ensure_ascii=False, indent=2), encoding="utf-8"
            )
            check("real Claude subprocess succeeded", state["status"] == "succeeded")
            check("isolated task worktree", Path(state["workspace"]) != repo)
            changes = http(path + "/changes", token)["changes"][0]
            report["changed_files"] = changes["files"]
            check(
                "only the permitted feature file changed",
                changes["files"] == ["backend/app/modules/user/normalization.py"],
            )
            check("real agent logs persisted", bool(logs))
            tests = http(path + "/tests", token, {})
            report["tests"] = {
                key: tests[key] for key in ("status", "exit_code", "output")
            }
            check(
                "independent acceptance tests and existing tests",
                tests["status"] == "passed" and "8 passed" in tests["output"],
            )
            http(path + "/commit", token, {})
            check(
                "leader review merge",
                http(f"/api/projects/p_demo/tasks/{task['task_id']}/merge", token, {})[
                    "merged"
                ],
            )
            interfaces = http("/api/projects/p_demo/interfaces", token)["interfaces"]
            check(
                "agent output enters shared interface registry",
                any(i["name"] == "normalize_username" for i in interfaces),
            )
            report["passed"] = True
        finally:
            process.terminate()
            process.wait(timeout=15)
            args.output.write_text(
                json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8"
            )
            print(f"Report: {args.output}; local diagnostics: {data}", flush=True)


if __name__ == "__main__":
    main()
